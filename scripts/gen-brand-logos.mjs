/* Generates app/components/catalog/brandLogos.ts — the white brand logos available per
   catalog section (public/catalog-page/logos/*.svg) with their viewBox aspect ratio.
   Brand lists are the marketing-approved order. Brands without a logo file are left out.
   Run: node scripts/gen-brand-logos.mjs */
import fs from "node:fs";
import path from "node:path";

const dir = "public/catalog-page/logos";
const files = new Set(fs.readdirSync(dir).filter((f) => f.endsWith(".svg")));
const slug = (s) => s.toLowerCase().replace(/&/g, "").replace(/[^a-z0-9]+/g, "");

/* explicit name → file overrides (file names chosen by the logo fetchers / pre-existing) */
const ALIAS = {
  "The North Face": "thenorthface",
  "New Era": "newera",
  "Hal's New York": "hals",
  "Hu Chocolate": "hu",
  "Tate's Bake Shop": "tates",
  "Rubik's": "rubiks",
  "Ray-Ban": "rayban",
  "Uncaged Ergonomics": "uncaged",
};

const LISTS = {
  swag: ["Nike", "Carhartt", "The North Face", "TravisMathew", "New Era", "Comfort Colors", "adidas", "Brooks Brothers", "OGIO", "Eddie Bauer", "Yeti", "Champion", "Columbia", "Moleskine", "Under Armour", "Stanley", "Cutter & Buck", "Peter Millar", "CamelBak", "JBL", "Hydro Flask", "Callaway", "Titleist", "Marmot"],
  snacks: ["Hal's New York", "Pretzel Pete", "Belgian Boys", "Pop Daddy Snacks", "The Gilded Nut", "Farmer's Pantry", "The Good Crisp", "Think Jerky", "Chunk Nibbles", "JoyRide", "Hu Chocolate", "Pipcorn", "SmartSweets", "Milk Bar", "The Yes Bar", "Michel et Augustin", "The Republic of Tea", "Craftmix", "Door County Coffee & Tea", "Field Trip", "Tate's Bake Shop", "Righteous Felon", "Dot's Pretzels", "Rip Van", "Hippeas", "Garrett Popcorn", "Beyond Good", "Super Coffee", "Moon Cheese", "House of Macadamias", "Swoon", "Stroop Club", "Poppi", "Jessie's Nutty Cups", "Nora Seaweed"],
  gifts: ["Brentwood", "Apple", "Pukka Pad", "STABILO", "Uncaged Ergonomics", "Patchology", "Boogie Board", "KeySmart", "Plant Therapy", "Rubik's", "Ostrichpillow", "Logitech", "Crayola", "Wild One", "Vivitar", "Grooming Lounge", "Fujifilm", "EcoTools", "My Arcade", "OXO", "Franklin Sports", "Godinger", "Burt's Bees", "Sony", "OtterBox", "WeatherTech", "Yeti", "Solo New York", "Travelon", "Casio", "Ray-Ban", "Audio-Technica", "Kobo"],
};

const ratioOf = (file) => {
  const s = fs.readFileSync(path.join(dir, file), "utf8");
  const vb = s.match(/viewBox="([\d.\-eE+\s,]+)"/);
  if (vb) {
    const [, , w, h] = vb[1].trim().split(/[\s,]+/).map(Number);
    if (w > 0 && h > 0) return Math.round((w / h) * 100) / 100;
  }
  const w = Number(s.match(/\swidth="([\d.]+)/)?.[1]);
  const h = Number(s.match(/\sheight="([\d.]+)/)?.[1]);
  return w && h ? Math.round((w / h) * 100) / 100 : 3;
};

const out = {};
const missing = {};
for (const [sec, names] of Object.entries(LISTS)) {
  out[sec] = [];
  missing[sec] = [];
  for (const name of names) {
    const base = ALIAS[name] ?? slug(name);
    const file = `${base}.svg`;
    if (files.has(file)) out[sec].push({ name, logo: `/catalog-page/logos/${file}`, ratio: ratioOf(file) });
    else missing[sec].push(name);
  }
}

const body = Object.entries(out)
  .map(([sec, list]) => `  ${sec}: [\n${list.map((b) => `    ${JSON.stringify(b)},`).join("\n")}\n  ],`)
  .join("\n");
fs.writeFileSync(
  "app/components/catalog/brandLogos.ts",
  `/* GENERATED by scripts/gen-brand-logos.mjs — do not edit. White brand marks per catalog section
   (public/catalog-page/logos), ratio = viewBox width ÷ height. */

export type BrandLogo = { name: string; logo: string; ratio: number };

export const BRAND_LOGOS: Record<"swag" | "gifts" | "snacks", BrandLogo[]> = {
${body}
};
`,
);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])), "missing:", missing);
